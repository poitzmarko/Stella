export const languageOptions = supportedLanguages;

export function t(lang: LanguageCode, key: TranslationKey): string {
  return dictionaries[lang]?.[key] ?? dictionaries.en[key] ?? key;
}

export function useI18n() {
  const [language, setLanguageState] = useState<LanguageCode>("de");

  useEffect(() => {
    const stored = window.localStorage.getItem("fx-pro-language");
    if (stored && supportedLanguages.some((item) => item.code === stored)) {
      setLanguageState(stored as LanguageCode);
      return;
    }

    const browser = navigator.language.split("-")[0];
    if (supportedLanguages.some((item) => item.code === browser)) {
      setLanguageState(browser as LanguageCode);
    }
  }, []);

  const setLanguage = (next: LanguageCode) => {
    setLanguageState(next);
    window.localStorage.setItem("fx-pro-language", next);
  };

  const dictionary = useMemo(
    () => dictionaries[language] ?? dictionaries.en,
    [language],
  );

  return {
    language,
    locale: language,
    setLanguage,
    setLocale: setLanguage,
    dictionary,
    languages: supportedLanguages,
    languageOptions,
    t: (key: TranslationKey | string) =>
      dictionary[key as TranslationKey] ?? dictionaries.en[key as TranslationKey] ?? key,
  };
}
